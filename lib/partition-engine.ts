// 2. Universal Auto-Partitioning Generator for any Indian City
export function generateAutoPartitions(
  city: CityOption,
  customCount?: number
): PartitionResult {
  if (city.id === "bengaluru" && (!customCount || customCount === 9)) {
    return getBengaluruCuratedPartitions()
  }

  const names = city.defaultDivisions || [
    "Central",
    "North",
    "North East",
    "East",
    "South East",
    "South",
    "South West",
    "West",
  ]

  const count = Math.min(
    Math.max(customCount ?? names.length, 3),
    12
  )

  const radiusLat = 0.12
  const radiusLng = 0.13

  // Generate outer boundary points for the city
  const boundarySteps = 24
  const cityBoundary: [number, number][] = []
  for (let i = 0; i <= boundarySteps; i++) {
    const angle = (i / boundarySteps) * Math.PI * 2
    const noise = 1 + 0.12 * Math.sin(angle * 3) + 0.08 * Math.cos(angle * 5)
    const lat = city.lat + Math.sin(angle) * radiusLat * noise
    const lng = city.lng + Math.cos(angle) * radiusLng * noise
    cityBoundary.push([Number(lat.toFixed(5)), Number(lng.toFixed(5))])
  }

  const divisions: CreateDivisionInput[] = []

  const hasCentral = count >= 5
  const outerSectorsCount = hasCentral ? count - 1 : count
  const innerRadiusLat = radiusLat * 0.36
  const innerRadiusLng = radiusLng * 0.36

  // Central division
  if (hasCentral) {
    const centralPolygon: [number, number][] = []
    const innerSteps = 12
    for (let i = 0; i <= innerSteps; i++) {
      const angle = (i / innerSteps) * Math.PI * 2
      const lat = city.lat + Math.sin(angle) * innerRadiusLat
      const lng = city.lng + Math.cos(angle) * innerRadiusLng
      centralPolygon.push([Number(lat.toFixed(5)), Number(lng.toFixed(5))])
    }

    divisions.push({
      id: `${city.id}-central`,
      name: names[0] || "Central Core",
      code: `${city.id.slice(0, 3).toUpperCase()}-CEN`,
      center_lat: Number(city.lat.toFixed(5)),
      center_lng: Number(city.lng.toFixed(5)),
      polygon_geojson: JSON.stringify(centralPolygon),
      sort_order: 1,
      is_active: true,
    })
  }

  // Outer sectors
  for (let s = 0; s < outerSectorsCount; s++) {
    const startAngle = (s / outerSectorsCount) * Math.PI * 2
    const endAngle = ((s + 1) / outerSectorsCount) * Math.PI * 2
    const midAngle = (startAngle + endAngle) / 2

    const sectorPolygon: [number, number][] = []

    const arcSteps = 6
    for (let j = 0; j <= arcSteps; j++) {
      const a = startAngle + (j / arcSteps) * (endAngle - startAngle)
      const noise = 1 + 0.12 * Math.sin(a * 3) + 0.08 * Math.cos(a * 5)
      const lat = city.lat + Math.sin(a) * radiusLat * noise
      const lng = city.lng + Math.cos(a) * radiusLng * noise
      sectorPolygon.push([Number(lat.toFixed(5)), Number(lng.toFixed(5))])
    }

    if (hasCentral) {
      for (let j = arcSteps; j >= 0; j--) {
        const a = startAngle + (j / arcSteps) * (endAngle - startAngle)
        const lat = city.lat + Math.sin(a) * innerRadiusLat
        const lng = city.lng + Math.cos(a) * innerRadiusLng
        sectorPolygon.push([Number(lat.toFixed(5)), Number(lng.toFixed(5))])
      }
    } else {
      sectorPolygon.push([Number(city.lat.toFixed(5)), Number(city.lng.toFixed(5))])
    }

    sectorPolygon.push(sectorPolygon[0])

    const divisionName =
      hasCentral
        ? names[s + 1] || `Zone ${s + 1}`
        : names[s] || `Zone ${s + 1}`

    const centerDist = hasCentral ? 0.65 : 0.55
    const centerLat = city.lat + Math.sin(midAngle) * radiusLat * centerDist
    const centerLng = city.lng + Math.cos(midAngle) * radiusLng * centerDist

    divisions.push({
      id: `${city.id}-${slug(divisionName)}`,
      name: divisionName,
      code: `${city.id.slice(0, 3).toUpperCase()}-Z${s + 1}`,
      center_lat: Number(centerLat.toFixed(5)),
      center_lng: Number(centerLng.toFixed(5)),
      polygon_geojson: JSON.stringify(sectorPolygon),
      sort_order: hasCentral ? s + 2 : s + 1,
      is_active: true,
    })
  }

  return { cityBoundary, divisions }
}

function slug(text: string): string {
  return text
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
}
